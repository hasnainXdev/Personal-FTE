def update_dashboard(vault_path: str) -> Dict[str, Any]:
    """
    Update dashboard with current status
    
    Args:
        vault_path: Path to Obsidian vault
        
    Returns:
        Dashboard status
    """
    logger.info('Updating dashboard')
    
    vault = Path(vault_path)
    dashboard_path = vault / 'Dashboard.md'
    
    if not dashboard_path.exists():
        return {
            'status': 'error',
            'message': 'Dashboard.md not found',
        }
    
    # Count items in each folder
    counts = {}
    folders = ['Needs_Action', 'Pending_Approval', 'In_Progress', 'Done']
    
    for folder in folders:
        folder_path = vault / folder
        if folder_path.exists():
            counts[folder] = len(list(folder_path.glob('*.md')))
        else:
            counts[folder] = 0
    
    # Update dashboard timestamp
    content = dashboard_path.read_text()
    content = content.replace(
        'last_updated: .*',
        f'last_updated: {datetime.now().isoformat()}'
    )
    dashboard_path.write_text(content)
    
    return {
        'status': 'success',
        'counts': counts,
        'updated': datetime.now().isoformat(),
    }


def cleanup_old_files(vault_path: str, days_old: int = 30) -> Dict[str, Any]:
    """
    Clean up old files from Done folder
    
    Args:
        vault_path: Path to Obsidian vault
        days_old: Move files older than this many days
        
    Returns:
        Cleanup summary
    """
    logger.info(f'Cleaning up files older than {days_old} days')
    
    vault = Path(vault_path)
    done_path = vault / 'Done'
    archive_path = vault / 'Archive'
    
    archive_path.mkdir(parents=True, exist_ok=True)
    
    cutoff = datetime.now() - timedelta(days=days_old)
    moved_count = 0
    
    if done_path.exists():
        for f in done_path.glob('*.md'):
            if datetime.fromtimestamp(f.stat().st_mtime) < cutoff:
                # Move to archive
                dest = archive_path / f.name
                f.rename(dest)
                moved_count += 1
    
    return {
        'status': 'success',
        'files_archived': moved_count,
        'cutoff_date': cutoff.strftime('%Y-%m-%d'),
    }
